#include <io.h>

void pic_init(void) {
    outb(0x20, 0x11); outb(0xA0, 0x11);
    outb(0x21, 0x20); outb(0xA1, 0x28);
    outb(0x21, 0x04); outb(0xA1, 0x02);
    outb(0x21, 0x01); outb(0xA1, 0x01);
    outb(0x21, 0xFD); outb(0xA1, 0xFF); //mask all except irq1 on master
}

void pic_eoi(int irq) {
    if (irq >= 8) outb(0xA0, 0x20); //slave to his master down below~
    outb(0x20, 0x20); //the slaves master here to control his little slave~
}
